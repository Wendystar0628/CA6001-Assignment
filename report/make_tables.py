"""Write the data-driven LaTeX tables of the report from ``results/``.

Run from the project root before compiling:

    .venv/Scripts/python.exe report/make_tables.py

Each table is written to ``report/tables/<name>.tex`` and pulled into the
report with ``\\input``. Edit the prose in ``report/sections/``; regenerate
these files whenever the results change.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "adaptive_v1"
OUT = ROOT / "report" / "tables"
OUT.mkdir(parents=True, exist_ok=True)

MAIN = ["gp", "xgb", "cnp", "tabpfn_joint", "tabpfn_graph"]
NAMES = {"gp": "GP", "xgb": "XGBoost residual", "cnp": "CNP", "tabpfn_joint": "TabPFN joint",
         "tabpfn_graph": "TabPFN + graph$^{\\dagger}$",
         "tabpfn_residual_unfinetuned": "\\quad Residual, pretrained weights",
         "tabpfn_residual_raw": "\\quad Residual, fine-tuned weights",
         "tabpfn_residual_guarded": "\\quad Residual, fine-tuned + sign guard",
         "tabpfn_joint_unfinetuned": "\\quad Joint, pretrained weights"}
ABLATION = ["tabpfn_residual_unfinetuned", "tabpfn_residual_raw", "tabpfn_residual_guarded",
            "tabpfn_joint_unfinetuned"]
EVAL = ["wellington_airport", "christchurch_stadium", "hollywood", "newlock"]
SITE = {"wellington_airport": "Wellington Airport", "christchurch_stadium": "Christchurch Stadium",
        "hollywood": "Hollywood", "newlock": "New Lock"}


def site_equal(df: pd.DataFrame, cols: list[str]) -> pd.DataFrame:
    """Mean within seed, then within site, then equally across sites."""
    a = df.groupby(["site_id", "seed", "model_id"])[cols].mean().groupby(["site_id", "model_id"]).mean()
    return a.groupby("model_id").mean()


def minus(text: str) -> str:
    return text.replace("-", "$-$")


def prediction_table() -> None:
    models = pd.read_csv(RES / "model_comparison.csv")
    ablation = pd.read_csv(RES / "ablation.csv")
    cols = ["log_mae", "thickness_mae_m", "recall", "fpr", "f1"]
    dev = site_equal(pd.concat([models[models.role == "development"], ablation[ablation.role == "development"]]), cols)
    ev = site_equal(pd.concat([models[models.role == "evaluation"], ablation[ablation.role == "evaluation"]]), cols)
    main_ev = ev.loc[MAIN]
    detect = main_ev[main_ev.recall > 0]  # CNP never predicts a low cell; its 0% FPR is not a merit
    best = {
        "dev_log": dev.loc[MAIN, "log_mae"].idxmin(), "dev_h": dev.loc[MAIN, "thickness_mae_m"].idxmin(),
        "log": main_ev.log_mae.idxmin(), "h": main_ev.thickness_mae_m.idxmin(),
        "recall": main_ev.recall.idxmax(), "fpr": detect.fpr.idxmin(), "f1": main_ev.f1.idxmax(),
    }

    def cell(model, key, value, fmt):
        text = format(value, fmt)
        return f"\\textbf{{{text}}}" if best.get(key) == model else text

    lines = []
    for m in MAIN + ["__rule__"] + ABLATION:
        if m == "__rule__":
            lines.append("\\midrule")
            lines.append("\\multicolumn{8}{l}{\\textit{TabPFN ablation (the fine-tuned joint row above completes the set)}}\\\\")
            continue
        lines.append(" & ".join([
            NAMES[m],
            cell(m, "dev_log", dev.loc[m, "log_mae"], ".3f"),
            cell(m, "dev_h", dev.loc[m, "thickness_mae_m"], ".3f"),
            cell(m, "log", ev.loc[m, "log_mae"], ".3f"),
            cell(m, "h", ev.loc[m, "thickness_mae_m"], ".3f"),
            cell(m, "recall", 100 * ev.loc[m, "recall"], ".1f"),
            cell(m, "fpr", 100 * ev.loc[m, "fpr"], ".1f"),
            cell(m, "f1", ev.loc[m, "f1"], ".2f"),
        ]) + "\\\\")
    body = "\n".join(lines)
    tex = rf"""% generated by report/make_tables.py -- do not edit by hand
\begin{{tabular}}{{@{{}}lrrrrrrr@{{}}}}
\toprule
 & \multicolumn{{2}}{{c}}{{Development (4 sites)}} & \multicolumn{{5}}{{c}}{{Evaluation (4 sites)}}\\
\cmidrule(lr){{2-3}}\cmidrule(l){{4-8}}
Method & log-MAE & Thick.\ (m) & log-MAE & Thick.\ (m) & Recall (\%) & FPR (\%) & F1\\
\midrule
{body}
\bottomrule
\end{{tabular}}
"""
    (OUT / "prediction.tex").write_text(tex, encoding="utf-8")


def decision_table() -> None:
    dec = pd.read_csv(RES / "decisions.csv")
    eco = pd.read_csv(RES / "economic_results.csv")
    models = pd.read_csv(RES / "model_comparison.csv")
    oracle = pd.read_csv(ROOT / "results" / "adaptive_v2_diagnostics" / "stopping_oracle_diagnostic.csv")
    dd = dec[dec.role == "evaluation"]
    e1 = eco[(eco.role == "evaluation") & (eco.alpha == 1.0)]
    rows, seq_sav, ada_sav, nets = [], [], [], []
    for s in EVAL:
        g = dd[dd.site_id == s]
        nf = int(g.n_full.iloc[0])
        audit = int(models[(models.role == "evaluation") & (models.site_id == s)].n_eval_locations.iloc[0])
        seq = g[g.policy_id == "B_seq"].n_stop.mean()
        ada = g[g.policy_id == "P_adapt"].n_stop.mean()
        seq_sav.append(100 * (nf - seq) / nf)
        ada_sav.append(100 * (nf - ada) / nf)
        ob = oracle[(oracle.site_id == s) & (oracle.policy_id == "P_adapt")].oracle_earliest_passing_budget
        orc = "none" if ob.isna().all() else (f"{int(ob.min())}" if ob.min() == ob.max()
                                               else f"{int(ob.min())}--{int(ob.max())}")
        passes = int(g[g.policy_id == "B_full"].audit_pass.sum())
        net = e1[(e1.site_id == s) & (e1.policy_id == "P_adapt")].net_benefit.mean() / 1000
        nets.append(net)
        rows.append(" & ".join([SITE[s], str(nf), str(audit), f"{seq:.1f}", f"{ada:.1f}",
                                f"{seq_sav[-1]:.1f}", f"{ada_sav[-1]:.1f}", f"{passes}/3", orc,
                                minus(f"{net:+.1f}")]) + "\\\\")
    rows.append("\\midrule")
    rows.append(" & ".join(["Equal-site mean", "", "", "", "", f"{sum(seq_sav) / 4:.1f}", f"{sum(ada_sav) / 4:.1f}",
                            "", "", minus(f"{sum(nets) / 4:+.1f}")]) + "\\\\")
    body = "\n".join(rows)
    tex = rf"""% generated by report/make_tables.py -- do not edit by hand
\begin{{tabular}}{{@{{}}lrrrrrrrrr@{{}}}}
\toprule
 & & & \multicolumn{{2}}{{c}}{{CPTs at stop}} & \multicolumn{{2}}{{c}}{{Saving (\%)}} & Full plan & Oracle & Net\\
\cmidrule(lr){{4-5}}\cmidrule(lr){{6-7}}
Site & $N_{{\text{{full}}}}$ & $|A|$ & Seq. & Adapt. & Seq. & Adapt. & passes & $N$ (adapt.) & k\euro\\
\midrule
{body}
\bottomrule
\end{{tabular}}
"""
    (OUT / "decisions.tex").write_text(tex, encoding="utf-8")


if __name__ == "__main__":
    prediction_table()
    decision_table()
    print("tables written to", OUT)
